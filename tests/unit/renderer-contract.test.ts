import { afterEach, expect, it, vi } from 'vitest';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { renderFiles } from '../../src/setup.js';

afterEach(() => {
  vi.unstubAllGlobals();
});

// Independent byte contract captured from setup.ts at e875ddc. Anchor to the
// historical module location, never to the implementation under test.
const anchor = new URL('../../src/setup.js', import.meta.url);
const quote = (value: string) => "'" + value.replaceAll("'", "'\\''") + "'";

it.each(['linux', 'darwin', 'win32'] as const)(
  'preserves complete rendered resources for %s, including captured paths',
  async (platform) => {
    const runtime = 'win32' === platform ? 'C:\\Node Runtime\\node.exe' : "/node's runtime/node";
    vi.stubGlobal('process', { ...process, platform, arch: 'x64', execPath: runtime });
    const commands = ['first', 'second'];
    const expected = new Map<string, string | Buffer>([
      [
        '.config/mise/conf.d/arch.toml',
        '# Generated by Arch.\n[env]\n_.path = ["{{config_root}}/.arch/bin"]\n',
      ],
      ['.arch/bin/.arch-router', 'arch-harness-router-v1\n'],
    ]);
    const cli = fileURLToPath(new URL('./cli.js', anchor));
    for (const command of commands) {
      if ('win32' === platform) {
        expected.set(
          `.arch/bin/${command}.exe`,
          await readFile(new URL('../vendor/shim-x64.exe', anchor)),
        );
        expected.set(
          `.arch/bin/${command}.shim`,
          `path = ${runtime}\nargs = "${cli}" run ${command} --\n`,
        );
      } else {
        expected.set(
          `.arch/bin/${command}`,
          `#!/bin/sh\nexec ${quote(runtime)} ${quote(cli)} run ${quote(command)} -- "$@"\n`,
        );
      }
    }
    expect([...(await renderFiles(commands))]).toEqual([...expected]);
  },
);

it('rejects unsupported Windows architectures before rendering a launcher', async () => {
  vi.stubGlobal('process', { ...process, platform: 'win32', arch: 'ia32' });
  await expect(renderFiles(['tool'])).rejects.toThrow('Windows bootstrap supports x64 and arm64');
});

it('keeps the supplied ARM64 executable bytes and shim payload without claiming ARM64 execution', async () => {
  const runtime = 'C:\\Arch Runtime\\node.exe';
  vi.stubGlobal('process', { ...process, platform: 'win32', arch: 'arm64', execPath: runtime });
  const resources = await renderFiles(['tool']);
  expect(resources.get('.arch/bin/tool.exe')).toEqual(
    await readFile(new URL('../vendor/shim-arm64.exe', anchor)),
  );
  expect(resources.get('.arch/bin/tool.shim')).toBe(
    `path = ${runtime}\nargs = "${fileURLToPath(new URL('./cli.js', anchor))}" run tool --\n`,
  );
});
