import { mkdir, readFile, writeFile, unlink, chmod } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { parseConfiguration } from './config.js';
import { routerMarker } from './process.js';

const configText = 'schema = 1\n\n[[middleware]]\nid = "demo"\nenabled = true\n';
const routePath = '.config/mise/conf.d/arch.toml';
const statePath = '.arch/bootstrap.json';
interface State { files: Record<string, string>; createdHarness: boolean }
const digest = (value: string | Buffer) => createHash('sha256').update(value).digest('hex');
const quote = (value: string) => "'" + value.replaceAll("'", "'\\''") + "'";

async function readOptional(file: string): Promise<Buffer | undefined> {
  try { return await readFile(file); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; }
}
function stateFrom(text: Buffer): State {
  const state = JSON.parse(text.toString()) as State;
  if (!state.files || typeof state.createdHarness !== 'boolean' || Object.entries(state.files).some(([file, hash]) =>
    !(file === routePath || /^\.arch\/bin\/[a-zA-Z0-9_.-]+$/.test(file)) || !/^[a-f0-9]{64}$/.test(hash))) throw new Error('Invalid bootstrap state');
  return state;
}
async function checkFiles(root: string, files: Record<string, string>) {
  for (const [file, hash] of Object.entries(files)) {
    const contents = await readOptional(join(root, file));
    if (!contents || digest(contents) !== hash) throw new Error(`Managed file changed; refusing to overwrite/remove: ${file}`);
  }
}

export async function setup(root: string, commands: readonly string[]): Promise<void> {
  root = resolve(root);
  if (!commands.length || new Set(commands.map(c => process.platform === 'win32' ? c.toLowerCase() : c)).size !== commands.length || commands.some(c => !/^[a-zA-Z][a-zA-Z0-9_-]*$/.test(c) || ['node', 'mise', 'arch'].includes(c.toLowerCase()))) {
    throw new Error('Supply unique executable names (node, mise, and arch are reserved)');
  }
  const cli = fileURLToPath(new URL('./cli.js', import.meta.url));
  const contents = new Map<string, string | Buffer>([
    [routePath, '# Generated by Arch.\n[env]\n_.path = ["{{config_root}}/.arch/bin"]\n'],
    ['.arch/bin/.arch-router', routerMarker]
  ]);
  for (const command of commands) {
    if (process.platform === 'win32') {
      if (!['x64', 'arm64'].includes(process.arch)) throw new Error('Windows bootstrap supports x64 and arm64');
      const shim = await readFile(new URL(`../vendor/shim-${process.arch}.exe`, import.meta.url));
      contents.set(`.arch/bin/${command}.exe`, shim);
      contents.set(`.arch/bin/${command}.shim`, `path = ${process.execPath}\nargs = "${cli}" run ${command} --\n`);
    } else {
      contents.set(`.arch/bin/${command}`, `#!/bin/sh\nexec ${quote(process.execPath)} ${quote(cli)} run ${quote(command)} -- "$@"\n`);
    }
  }
  const files = Object.fromEntries([...contents].map(([file, text]) => [file, digest(text)]));
  const harnessFile = join(root, '.arch/harness.toml'), stateFile = join(root, statePath);
  const [existingHarness, existingState] = await Promise.all([readOptional(harnessFile), readOptional(stateFile)]);
  if (existingHarness !== undefined) parseConfiguration(existingHarness.toString(), root);
  if (existingState) {
    const state = stateFrom(existingState);
    if (JSON.stringify(state.files) !== JSON.stringify(files)) throw new Error('Arch setup differs; uninstall before changing routed commands');
    await checkFiles(root, state.files);
    return;
  }
  for (const file of contents.keys()) if (await readOptional(join(root, file))) throw new Error(`Refusing to overwrite ${file}`);
  const created: string[] = [];
  try {
    for (const [file, text] of [...contents, ...(existingHarness === undefined ? [['.arch/harness.toml', configText] as const] : []),
      [statePath, JSON.stringify({ files, createdHarness: existingHarness === undefined } satisfies State, null, 2) + '\n'] as const]) {
      const target = join(root, file);
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, text, { flag: 'wx' });
      created.push(target);
      if (file.startsWith('.arch/bin/') && process.platform !== 'win32') await chmod(target, 0o755);
    }
  } catch (error) {
    for (const file of created.reverse()) await unlink(file);
    throw error;
  }
}

export async function uninstall(root: string): Promise<void> {
  root = resolve(root);
  const stateFile = join(root, statePath), text = await readOptional(stateFile);
  if (!text) return;
  const state = stateFrom(text);
  await checkFiles(root, state.files);
  for (const file of Object.keys(state.files)) await unlink(join(root, file));
  const harnessFile = join(root, '.arch/harness.toml');
  if (state.createdHarness && (await readOptional(harnessFile))?.toString() === configText) await unlink(harnessFile);
  await unlink(stateFile);
}
